"""
search/engines/dark_ahmia.py
Ahmia Tor & Dark Web search engine adapter.
Queries Ahmia with anti-bot token bypass and unmoderated link discovery.
"""
from __future__ import annotations

import time
import logging
import urllib.parse
from typing import List, Dict, Optional

from .base import BaseEngine
from ..models import SearchQuery, SearchResult
from .. import http_client

try:
    from hecos.core.logging import logger as hecos_logger
except ImportError:
    hecos_logger = logging.getLogger("browser.search.engines.ahmia")
logger = hecos_logger

# Default V3 Onion address and clearnet mirror for Ahmia
DEFAULT_AHMIA_ONION = "http://juhanurmihxlp77nkq76byazcldy2hlmovfu2epvl5ankdibsot4csyd.onion"
DEFAULT_AHMIA_CLEAR = "https://ahmia.fi"

_cached_token: Optional[Dict[str, str]] = None
_cached_token_ts: float = 0.0


def _get_ahmia_urls() -> tuple[str, str]:
    """Retrieves Ahmia onion and clearnet URLs from search configuration."""
    from ..config import get_search_config
    cfg = get_search_config().get("endpoints", {}).get("dark_ahmia", {})
    clear = cfg.get("clearnet_url") or DEFAULT_AHMIA_CLEAR
    onion = cfg.get("onion_url") or DEFAULT_AHMIA_ONION
    return clear.rstrip("/"), onion.rstrip("/")


def _get_ahmia_tokens() -> Dict[str, str]:
    """
    Fetches the dynamic anti-bot honeypot token generated by Ahmia on its homepage.
    Without this token, Ahmia returns an empty search page.
    """
    global _cached_token, _cached_token_ts
    now = time.time()
    if _cached_token and (now - _cached_token_ts < 900):  # 15 minutes TTL
        return dict(_cached_token)

    clear_url, _ = _get_ahmia_urls()
    tokens: Dict[str, str] = {}
    try:
        headers = {
            "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36",
            "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
            "Referer": f"{clear_url}/"
        }
        resp = http_client.get(f"{clear_url}/", network="clearnet", headers=headers, timeout=8)
        if resp.status_code == 200:
            from bs4 import BeautifulSoup
            soup = BeautifulSoup(resp.text, "lxml")
            form = soup.find("form")
            if form:
                for inp in form.find_all("input"):
                    name = inp.get("name")
                    val = inp.get("value", "")
                    if name and name != "q":
                        tokens[name] = val
        if tokens:
            _cached_token = tokens
            _cached_token_ts = now
            hecos_logger.debug(f"[DarkAhmia] Extracted dynamic form token: {tokens}")
    except Exception as e:
        hecos_logger.debug(f"[DarkAhmia] Failed to extract dynamic form token: {e}")

    return tokens


class DarkAhmiaEngine(BaseEngine):
    """Ahmia dark web (.onion) search engine."""

    def __init__(self):
        super().__init__(
            engine_id="dark_ahmia",
            name="Ahmia (Dark Web / Tor)",
            category="onion",
            network="tor",
            priority=90
        )

    def is_available(self) -> bool:
        from ..config import get_search_config
        cfg = get_search_config().get("tor", {})
        if not cfg.get("enabled", False):
            return False
        return True

    def search(self, query: SearchQuery) -> List[SearchResult]:
        results: List[SearchResult] = []
        tor_online = http_client.is_tor_online()

        tokens = _get_ahmia_tokens()
        params = dict(tokens)
        params["q"] = query.query

        clear_url, onion_url = _get_ahmia_urls()
        headers = {
            "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36",
            "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
            "Referer": f"{clear_url}/",
            "Upgrade-Insecure-Requests": "1"
        }

        # Query clearnet mirror with token first (extremely fast), or fallback to onion
        search_urls = [
            (f"{clear_url}/search/", "clearnet"),
        ]
        if tor_online:
            search_urls.append((f"{onion_url}/search/", "tor"))

        is_unlimited = (query.limit is not None and query.limit <= 0)
        target_limit = 100000 if is_unlimited else query.limit
        max_pages = 20 if is_unlimited else min(20, max(1, (target_limit // 40) + 1))

        for base_url, net in search_urls:
            hecos_logger.info(f"[SEARCH:AHMIA] Querying Ahmia via {net}: '{query.query}' (target={'UNLIMITED' if is_unlimited else target_limit}, max_pages={max_pages})...")
            try:
                current_page = 1
                while current_page <= max_pages:
                    page_params = dict(params)
                    if current_page > 1:
                        page_params["page"] = current_page

                    resp = http_client.get(base_url, network=net, params=page_params, headers=headers, timeout=query.timeout)
                    if resp.status_code != 200:
                        break

                    from bs4 import BeautifulSoup
                    soup = BeautifulSoup(resp.text, "lxml")

                    items = soup.find_all("li", class_="result")
                    if not items:
                        break

                    page_added = 0
                    for it in items:
                        if len(results) >= target_limit:
                            break
                        h4 = it.find("h4")
                        p = it.find("p")
                        cite = it.find("cite")

                        if h4 and h4.find("a"):
                            a_tag = h4.find("a")
                            raw_href = a_tag.get("href", "")
                            title = a_tag.get_text(strip=True)

                            # Clean redirect URL if necessary (e.g. /search/redirect?search_term=...&redirect_url=...)
                            if "redirect_url=" in raw_href or "url=" in raw_href:
                                parsed = urllib.parse.parse_qs(urllib.parse.urlparse(raw_href).query)
                                final_url = parsed.get("redirect_url", parsed.get("url", [raw_href]))[0]
                            else:
                                final_url = raw_href

                            snippet = p.get_text(strip=True) if p else ""
                            domain = cite.get_text(strip=True) if cite else ""

                            if final_url.startswith("/"):
                                final_url = urllib.parse.urljoin(base_url, final_url)

                            if final_url and ".onion" in final_url:
                                results.append(SearchResult(
                                    title=title or domain or "Onion Service",
                                    url=final_url,
                                    snippet=snippet,
                                    engine="ahmia:tor",
                                    category="onion",
                                    network="tor",
                                    metadata={"onion_domain": domain}
                                ))
                                page_added += 1

                    if len(results) >= target_limit or page_added == 0:
                        break
                    current_page += 1

                if results:
                    hecos_logger.info(f"[DarkAhmia] Successfully retrieved {len(results)} .onion results across pages via {net}")
                    return results
            except Exception as e:
                logger.warning(f"[DarkAhmia] Search query via {net} failed: {e}")

        return results
